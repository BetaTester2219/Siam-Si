const app = document.querySelector("#app");

function t(key) {
  return i18n[state.lang][key];
}

function drawFortuneNumber(previousNumber = state.selectedNumber) {
  const { min, max } = fortuneNumberRange;
  const total = max - min + 1;
  if (total <= 1) return min;

  let next = previousNumber;
  while (next === previousNumber) {
    next = Math.floor(Math.random() * total) + min;
  }
  return next;
}

function currentResultTitle() {
  return t("resultTitle").replace("{number}", state.selectedNumber);
}

function currentFortuneReading() {
  const reading = fortuneReadings[state.selectedNumber] || fortuneReadings[1];
  const localized = reading[state.lang] || reading.th;
  const [fortune, work, money, love, health] = localized;
  return { fortune, work, money, love, health };
}

function setScreen(screen, direction = "forward") {
  clearTimer();
  state.screen = screen;
  state.transition = direction;
  if (screen === "shake") {
    state.shakeState = "idle";
    state.shakeScore = 0;
    state.lastVector = null;
  }
  render();
}

function clearTimer() {
  if (state.timer) {
    clearTimeout(state.timer);
    state.timer = null;
  }
}

function setLang(lang) {
  state.lang = lang;
  document.documentElement.lang = lang;
  state.transition = "none";
  render();
}

function back() {
  const route = {
    temples: "welcome",
    intro: "temples",
    permission: "temples",
    shake: "permission",
    reveal: "shake",
    result: "reveal",
  };
  setScreen(route[state.screen] || "welcome", "back");
}

function render() {
  const views = {
    welcome: welcomeView,
    temples: templesView,
    intro: introView,
    permission: permissionView,
    shake: shakeView,
    reveal: revealView,
    result: resultView,
  };

  app.innerHTML = views[state.screen]();
  const screen = app.querySelector(".screen");
  if (screen && state.transition !== "none") {
    screen.classList.add("page-enter", state.transition === "back" ? "from-left" : "from-right");
  }
  state.transition = "none";
  bindEvents();
}

