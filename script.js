function bindEvents() {
  document.querySelectorAll("[data-screen]").forEach((button) => {
    button.addEventListener("click", () => setScreen(button.dataset.screen));
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => setLang(button.dataset.lang));
  });

  document.querySelectorAll("[data-action='back']").forEach((button) => {
    button.addEventListener("click", back);
  });

  document.querySelector("[data-action='enable-motion']")?.addEventListener("click", enableMotion);
  document.querySelector("[data-action='save']")?.addEventListener("click", () => toast(t("savedToast")));
  document.querySelector("[data-action='share']")?.addEventListener("click", shareFortune);
}

async function enableMotion() {
  try {
    const motion = window.DeviceMotionEvent;
    if (!motion) {
      state.motionEnabled = false;
      setScreen("shake");
      return;
    }

    if (typeof motion.requestPermission === "function") {
      const response = await motion.requestPermission();
      if (response !== "granted") {
        state.motionEnabled = false;
        setScreen("shake");
        return;
      }
    }

    window.addEventListener("devicemotion", onDeviceMotion, { passive: true });
    state.motionEnabled = true;
    setScreen("shake");
  } catch {
    state.motionEnabled = false;
    setScreen("shake");
  }
}

function onDeviceMotion(event) {
  if (state.screen !== "shake" || state.shakeState === "selected" || state.shakeState === "drawing") return;

  const acceleration = event.accelerationIncludingGravity;
  if (!acceleration) return;

  const now = Date.now();
  const vector = {
    x: acceleration.x || 0,
    y: acceleration.y || 0,
    z: acceleration.z || 0,
  };

  if (!state.lastVector) {
    state.lastVector = vector;
    return;
  }

  const force =
    Math.abs(vector.x - state.lastVector.x) +
    Math.abs(vector.y - state.lastVector.y) +
    Math.abs(vector.z - state.lastVector.z);
  state.lastVector = vector;

  if (force > 11 && now - state.lastMotion > 120) {
    state.lastMotion = now;
    state.shakeScore += Math.min(force / 6, 3.4);
    updateShakeState();
  }
}

function updateShakeState() {
  const next = state.shakeScore > 10 ? "strong" : state.shakeScore > 4 ? "shaking" : "light";
  if (state.shakeState !== next) {
    state.shakeState = next;
    render();
  }

  clearTimer();
  state.timer = setTimeout(() => {
    if (state.screen === "shake" && state.shakeState !== "selected" && state.shakeState !== "drawing") {
      state.shakeScore = Math.max(0, state.shakeScore - 2.5);
      if (state.shakeScore <= 0) {
        state.shakeState = "idle";
        render();
      }
    }
  }, 820);

  if (state.shakeScore >= 16) {
    selectFortune();
  }
}

function selectFortune() {
  state.selectedNumber = drawFortuneNumber();
  state.shakeState = "drawing";
  render();

  if ("vibrate" in navigator) {
    navigator.vibrate([28, 42, 35]);
  }

  state.timer = setTimeout(() => {
    state.shakeState = "selected";
    render();
    state.timer = setTimeout(() => setScreen("reveal"), 2600);
  }, 900);
}

async function shareFortune() {
  const text = `${currentResultTitle()} - ${t("fortuneText")}`;
  if (navigator.share) {
    try {
      await navigator.share({ title: currentResultTitle(), text });
      return;
    } catch {
      // Keep the prototype quiet if the share sheet is dismissed.
    }
  }
  toast(t("sharedToast"));
}

function toast(message) {
  document.querySelector(".toast")?.remove();
  const el = document.createElement("div");
  el.className = "toast";
  el.textContent = message;
  document.body.appendChild(el);
  requestAnimationFrame(() => el.classList.add("show"));
  setTimeout(() => {
    el.classList.remove("show");
    setTimeout(() => el.remove(), 260);
  }, 1900);
}

